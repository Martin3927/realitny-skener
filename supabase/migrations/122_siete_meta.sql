-- =====================================================================
-- Facebook a Instagram kancelárie priamo cez Meta (bez Make).
-- Administrátor kancelárie sa v Týpkovi (Vzhľad → Facebook a Instagram kancelárie) prihlási Facebookom
-- a vyberie stránku; funkcia meta uloží kľúč stránky, funkcia siete potom zverejňuje priamo cez Graph API.
-- Kancelária bez prepojenia zverejňuje ako doteraz cez Make (nastavenia_kancelarie.make_siete_webhook).
--
-- Kľúče stránok sú zašifrované (AES-GCM) vo funkciách – kľúč na šifrovanie je len v tajomstvách funkcií
-- (SIETE_KLUC, inak odvodený z META_APP_SECRET). Tabuľky číta a zapisuje len server (service role);
-- aplikácia vidí len stav cez siete_prepojenie() – bez kľúčov.
-- =====================================================================

create table if not exists public.siete_prepojenia (
  kancelaria_id bigint primary key references public.kancelarie(id) on delete cascade,
  fb_page_id text not null,
  fb_page_nazov text,
  fb_page_token text not null,          -- zašifrovaný kľúč stránky
  ig_id text,                           -- Instagram (profesionálny účet) prepojený so stránkou
  ig_meno text,
  fb_user_id text,                      -- kto sa prihlásil (pre žiadosť o vymazanie údajov z Facebooku)
  fb_user_meno text,
  pripojil uuid references public.makleri(id) on delete set null,
  pripojene timestamptz not null default now(),
  chyba text,                           -- Facebook prestal kľúč prijímať (zmena hesla, odobratá rola…)
  chyba_kedy timestamptz
);
alter table public.siete_prepojenia enable row level security;
revoke all on table public.siete_prepojenia from public, anon, authenticated;

-- rozbehnuté prihlásenia (náhodný „state“ – v databáze len jeho odtlačok sha256); platia 30 minút
create table if not exists public.siete_prihlasenia (
  id bigint generated by default as identity primary key,
  stav_hash text not null unique,
  kancelaria_id bigint not null references public.kancelarie(id) on delete cascade,
  makler_id uuid not null references public.makleri(id) on delete cascade,
  vytvorene timestamptz not null default now(),
  stranky text,                         -- zašifrovaný zoznam stránok s kľúčmi, keď treba vybrať jednu z viacerých
  fb_user_id text,
  fb_user_meno text,
  hotovo boolean not null default false
);
create index if not exists siete_prihlasenia_makler on public.siete_prihlasenia (makler_id, vytvorene desc);
alter table public.siete_prihlasenia enable row level security;
revoke all on table public.siete_prihlasenia from public, anon, authenticated;
revoke all on sequence public.siete_prihlasenia_id_seq from public, anon, authenticated;

-- stav prepojenia aktívnej kancelárie pre aplikáciu (bez kľúčov)
create or replace function public.siete_prepojenie() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  k bigint := aktivna_kancelaria();
  p siete_prepojenia;
begin
  perform _over_aktivny();
  select * into p from siete_prepojenia where kancelaria_id = k;
  return jsonb_build_object(
    'meta', case when p.kancelaria_id is null then null else jsonb_build_object(
      'stranka', p.fb_page_nazov, 'stranka_id', p.fb_page_id,
      'instagram', p.ig_meno, 'ma_instagram', p.ig_id is not null,
      'pripojil', _meno(p.pripojil), 'pripojene', p.pripojene,
      'chyba', p.chyba, 'chyba_kedy', p.chyba_kedy) end,
    'make', exists (select 1 from nastavenia_kancelarie n
                    where n.kancelaria_id = k and n.kluc = 'make_siete_webhook' and coalesce(n.hodnota, '') <> ''));
end $$;
revoke execute on function public.siete_prepojenie() from public, anon;
grant execute on function public.siete_prepojenie() to authenticated, service_role;
