create trigger nastav_kancelariu before insert on public.odhady_hodnoty for each row execute function public._nastav_kancelariu();
drop trigger if exists zz_straz_kancelariu on public.odhady_hodnoty;
create trigger zz_straz_kancelariu before insert or update or delete on public.odhady_hodnoty for each row execute function public._straz_kancelariu();

alter table public.odhady_hodnoty enable row level security;
drop policy if exists odhady_hodnoty_citat on public.odhady_hodnoty;
create policy odhady_hodnoty_citat on public.odhady_hodnoty for select to authenticated
  using (ja_aktivny() and (ja_admin() or makler_id = (select auth.uid())));
