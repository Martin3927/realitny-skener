--  * e-maily posiela funkcia pripomienky: potvrdenie klientovi hneď po odoslaní a odhad od makléra
--  * údaje najdlhšie 2 roky (ako ostatné žiadosti z portálu), odtlačok sieťovej adresy 7 dní

-- ---------------------------------------------------------------- tabuľka
create table if not exists public.odhady_hodnoty (
  id bigint generated by default as identity primary key,
  kancelaria_id bigint not null references public.kancelarie(id),
  makler_id uuid references public.makleri(id) on delete set null,
  web_kontakt_id bigint references public.web_kontakty(id) on delete set null,
  vytvorene timestamptz not null default now(),
  upravene timestamptz not null default now(),
  -- nehnuteľnosť (z formulára)
  typ text not null check (typ in ('byt', 'dom', 'pozemok', 'ine')),
  nazov text,                         -- „3-izbový byt, 68 m², Spišská Nová Ves“ (pre zoznam, zvonček a e-maily)
  kraj text, okres text, obec text not null, cast_obce text, ulica text, cislo text,
  plocha numeric, pozemok numeric, izby text, poschodie integer, poschodi integer,
  druh_pozemku text, popis text, stav_nehn text,
  siete text[] not null default '{}', doplnky text[] not null default '{}',
  dovod text, poznamka text,
  -- klient
  meno text not null, telefon text, email text,
  odkial text,                        -- reklama / odkaz, odkiaľ prišiel (utm_…, fbclid, gclid, cudzia stránka)
  odtlacok text,                      -- odtlačok sieťovej adresy (ochrana proti robotom), po 7 dňoch sa maže
  auto jsonb,                         -- orientačný výpočet zo skenera v čase žiadosti (_odhad_ceny) – vidí len maklér
  -- práca makléra
  stav text not null default 'nova' check (stav in ('nova', 'kontaktovany', 'odoslany', 'obhliadka', 'zakazka', 'vykup', 'bez_obchodu')),
  cena_od integer, cena_do integer, text_klientovi text, poznamka_maklera text,
  kontaktovane timestamptz,
  -- e-maily (funkcia pripomienky)
  potvrdenie_poslat boolean not null default false, potvrdenie_odoslane timestamptz, potvrdenie_chyba text,
  email_poslat timestamptz, email_odoslany timestamptz, email_chyba text, email_kto uuid
);
create index if not exists odhady_hodnoty_kancelaria on public.odhady_hodnoty (kancelaria_id);
create index if not exists odhady_hodnoty_makler on public.odhady_hodnoty (makler_id, vytvorene desc);
create index if not exists odhady_hodnoty_kontakt on public.odhady_hodnoty (web_kontakt_id);
create index if not exists odhady_hodnoty_emaily on public.odhady_hodnoty (id) where potvrdenie_poslat or (email_poslat is not null and email_odoslany is null and email_chyba is null);

-- kancelária podľa makléra a stráž kancelárie ako pri ostatných tabuľkách (095, 096)
