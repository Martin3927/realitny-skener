-- ODDELENIE KANCELÁRIÍ – 1. krok: základ (správanie Týpka sa nemení)
-- * tabuľka kancelárií, Alpha Reality = kancelária 1 (všetko dnešné jej patrí)
-- * každý maklér a každý záznam, ktorý patrí kancelárii, má stĺpec kancelaria_id
-- * nový záznam dostane kanceláriu sám (trigger): podľa makléra, ponuky, webu, dopytu alebo sídliska,
--   inak podľa prihláseného; keď sa nedá zistiť, zatiaľ Alpha Reality (v 2. kroku sa taký zápis zastaví)
-- Pravidlá prístupu (kto čo vidí) sa menia až v 2. kroku. Pravidlo používateľa: z kancelárie von nejde nič –
-- telefóny predajcov, prevzatia, hovory, poznámky, označenia RK, klienti, ponuky, chat, kalendár, web, štatistiky.
-- Spoločné ostáva: inzeráty súkromníkov zo skenera (inzeraty, inzeraty_ai, odhady, archiv), číselníky
-- (lokality, uc_*, meniny), radar_*, stav_skenera, skener_strazca, novinky Týpka, portal_*, zakaznici (hlavný správca).
-- Stĺpec sa pridáva s pevnou predvolenou hodnotou (bez prepisovania riadkov a bez spúšťania triggerov na úpravu),
-- potom sa predvolená hodnota zruší – ďalšie riadky dopĺňa trigger.

create table if not exists public.kancelarie (
  id bigint generated by default as identity primary key,
  nazov text not null,
  typ text not null default 'kancelaria' check (typ in ('kancelaria', 'makler')),
  zakaznik_id bigint unique references public.zakaznici(id) on delete set null,
  okresy text[] not null default '{}',
  aktivna boolean not null default true,
  vytvorene timestamptz not null default now()
);
insert into public.kancelarie (id, nazov, typ, okresy)
values (1, 'Alpha Reality', 'kancelaria', array['Spišská Nová Ves', 'Levoča'])
on conflict (id) do nothing;
select setval(pg_get_serial_sequence('public.kancelarie', 'id'), greatest(1, (select max(id) from public.kancelarie)));

-- makléri: kým nie je vytváranie účtov pre iné kancelárie (4. krok), nový maklér patrí do Alpha Reality
alter table public.makleri add column if not exists kancelaria_id bigint not null default 1 references public.kancelarie(id);
create index if not exists makleri_kancelaria on public.makleri (kancelaria_id);

-- kancelária prihláseného
create or replace function public.moja_kancelaria() returns bigint
language sql stable security definer set search_path = public as $$
  select kancelaria_id from makleri where id = auth.uid()
$$;
revoke execute on function public.moja_kancelaria() from public, anon;
grant execute on function public.moja_kancelaria() to authenticated, service_role;

alter table public.kancelarie enable row level security;
revoke all on public.kancelarie from public, anon;
grant select on public.kancelarie to authenticated;
drop policy if exists kancelarie_citat on public.kancelarie;
create policy kancelarie_citat on public.kancelarie for select to authenticated
  using (id = public.moja_kancelaria() or public.je_hlavny_spravca());

-- nový záznam dostane kanceláriu: maklér (makler_id, oznacil, zadal, od_id, od, kto, vytvoril, upravil)
-- → ponuka (nehnutelnost_id) → web (web_id) → dopyt (dopyt_id) → sídlisko (sidlisko_id) → prihlásený → Alpha Reality
create or replace function public._nastav_kancelariu() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  j jsonb;
  k text;
  v bigint;
begin
  if new.kancelaria_id is not null then return new; end if;
  j := to_jsonb(new);
  begin
    foreach k in array array['makler_id', 'oznacil', 'zadal', 'od_id', 'od', 'kto', 'vytvoril', 'upravil'] loop
      if j ? k and nullif(j ->> k, '') is not null then
        select m.kancelaria_id into v from makleri m where m.id = (j ->> k)::uuid;
      end if;
      exit when v is not null;
    end loop;
    if v is null and nullif(j ->> 'nehnutelnost_id', '') is not null then
      select n.kancelaria_id into v from nehnutelnosti n where n.id = (j ->> 'nehnutelnost_id')::bigint;
    end if;
    if v is null and nullif(j ->> 'web_id', '') is not null then
      select w.kancelaria_id into v from weby w where w.id = (j ->> 'web_id')::bigint;
    end if;
    if v is null and nullif(j ->> 'dopyt_id', '') is not null then
      select d.kancelaria_id into v from dopyty d where d.id = (j ->> 'dopyt_id')::bigint;
    end if;
    if v is null and nullif(j ->> 'sidlisko_id', '') is not null then
      select s.kancelaria_id into v from sidliska s where s.id = (j ->> 'sidlisko_id')::bigint;
    end if;
    if v is null then v := moja_kancelaria(); end if;
  exception when others then
    v := null;
  end;
  new.kancelaria_id := coalesce(v, 1);
  return new;
end $$;
revoke execute on function public._nastav_kancelariu() from public, anon, authenticated;

do $$
declare
  t text;
begin
  foreach t in array array[
    'ai_rozhovory', 'ai_texty', 'aktivity', 'asistent_pouzitie', 'cas_posledny_zapis', 'cas_v_aplikacii', 'chat_reakcie',
    'dopyty', 'dopyty_kontakty', 'historia_zmien', 'makler_osobne', 'makleri_kalendar', 'matterport_rezervacie',
    'nehnutelnosti', 'nehnutelnosti_interne', 'obhliadky', 'oznacenia', 'pochvaly', 'predajcovia', 'prevzatia',
    'pripomienky', 'prispevky_siete', 'provizie', 'reakcie', 'recenzie', 'schrankovanie', 'schrankovanie_akcie',
    'sidliska', 'sidliska_poznamky', 'spravy', 'sukromne_spravy', 'telefony', 'udalosti', 'web_domena_dotazy',
    'web_kliky', 'web_kontakty', 'web_navstevnici', 'web_strazca_fronta', 'web_strazcovia', 'web_zdroje',
    'web_zobrazenia', 'weby', 'weby_stare_adresy', 'weby_verzie', 'zhody_oznamene', 'zobrazenia_ponuk'
  ] loop
    if to_regclass('public.' || t) is null then
      raise notice 'tabuľka % neexistuje – preskakujem', t;
      continue;
    end if;
    execute format('alter table public.%I add column if not exists kancelaria_id bigint not null default 1 references public.kancelarie(id)', t);
    execute format('alter table public.%I alter column kancelaria_id drop default', t);
    execute format('create index if not exists %I on public.%I (kancelaria_id)', t || '_kancelaria', t);
    execute format('drop trigger if exists nastav_kancelariu on public.%I', t);
    execute format('create trigger nastav_kancelariu before insert on public.%I for each row execute function public._nastav_kancelariu()', t);
  end loop;
end $$;
