-- ---------------------------------------------------------------- strážca kancelárie: prevzatie kontaktu
create or replace function public._straz_kancelariu() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  v_ja uuid := auth.uid();
  v_smie bigint[];
begin
  if v_ja is null or not exists (select 1 from makleri where id = v_ja) then
    return case when tg_op = 'DELETE' then old else new end;
  end if;
  -- kontakty na predaj (117): žiadosť v skrytej kancelárii zakladá odhad_ziadost a prevzatie (_kontakt_odovzdaj) ju presúva
  -- do kancelárie kupujúceho – len s príznakom, ktorý nastavujú tieto funkcie (z aplikácie sa nastaviť nedá)
  if tg_table_name = 'odhady_hodnoty' and current_setting('typek.trh', true) = 'ano' then
    if tg_op = 'INSERT' then
      if new.kancelaria_id = (select kancelaria_trh from kontakty_nastavenie where id = 1) then return new; end if;
    elsif tg_op = 'UPDATE' then
      if old.kancelaria_id = (select kancelaria_trh from kontakty_nastavenie where id = 1)
         and (new.kancelaria_id = old.kancelaria_id or new.kancelaria_id = moja_kancelaria() or je_hlavny_spravca()) then
        return new;
      end if;
    end if;
  end if;
  v_smie := array[aktivna_kancelaria(), moja_kancelaria()];
  if tg_op in ('UPDATE', 'DELETE') and not (old.kancelaria_id = any(v_smie)) then
    raise exception 'Tento záznam patrí inej kancelárii.' using errcode = '42501';
  end if;
  if tg_op in ('INSERT', 'UPDATE') and not (new.kancelaria_id = any(v_smie)) then
    raise exception 'Záznam sa nedá uložiť do inej kancelárie.' using errcode = '42501';
  end if;
  if tg_op = 'UPDATE' and new.kancelaria_id is distinct from old.kancelaria_id and not je_hlavny_spravca() then
    raise exception 'Záznam sa nedá presunúť do inej kancelárie.' using errcode = '42501';
  end if;
  return case when tg_op = 'DELETE' then old else new end;
end $$;
revoke execute on function public._straz_kancelariu() from public, anon, authenticated;

-- ---------------------------------------------------------------- pomocníci
-- cena teraz: posledný krok, ktorého čas už uplynul (pred začiatkom prvá cena)
create or replace function public._kontakt_cena(p_ceny jsonb, p_od timestamptz) returns integer
language sql stable as $$
  select coalesce(
    (select (e->>'c')::int from jsonb_array_elements(p_ceny) e
      where p_od + (e->>'h')::float8 * interval '1 hour' <= now() order by (e->>'h')::float8 desc limit 1),
    (select (e->>'c')::int from jsonb_array_elements(p_ceny) e order by (e->>'h')::float8 limit 1))
$$;
-- najbližšie zlacnenie {c, kedy} (null = už je najnižšia cena)
create or replace function public._kontakt_dalsia(p_ceny jsonb, p_od timestamptz) returns jsonb
language sql stable as $$
  select jsonb_build_object('c', (e->>'c')::int, 'kedy', p_od + (e->>'h')::float8 * interval '1 hour')
    from jsonb_array_elements(p_ceny) e
   where p_od + (e->>'h')::float8 * interval '1 hour' > now()
     and (e->>'c')::int < _kontakt_cena(p_ceny, p_od)
   order by (e->>'h')::float8 limit 1
$$;
-- začiatok ceny: hneď, v noci (21:00 – 7:00) od 7:00
create or replace function public._kontakt_start(p_kedy timestamptz) returns timestamptz
language sql stable as $$
  select case when extract(hour from p_kedy at time zone 'Europe/Bratislava') between 7 and 20 then p_kedy
    else (date_trunc('day', p_kedy at time zone 'Europe/Bratislava')
          + case when extract(hour from p_kedy at time zone 'Europe/Bratislava') >= 21 then interval '1 day' else interval '0' end
          + interval '7 hours') at time zone 'Europe/Bratislava' end
$$;

-- kancelárie, ktoré kontakty z okresu kupujú (aktívne, platiace, so sekciou Odhady, okres medzi svojimi)
create or replace function public._kontakty_kancelarie(p_okres text) returns setof bigint
language sql stable security definer set search_path = public as $$
  select k.id from kancelarie k
   where k.aktivna and p_okres = any(k.okresy) and _kancelaria_platna(k.id) and (k.sekcie is null or 'odhady' = any(k.sekcie))
     and k.id is distinct from (select kancelaria_trh from kontakty_nastavenie where id = 1)
     and exists (select 1 from makleri m where m.kancelaria_id = k.id and m.aktivny)
$$;
-- makléri, ktorým príde do mobilu nový kontakt na predaj
create or replace function public._kontakty_kupci(p_okres text) returns uuid[]
language sql stable security definer set search_path = public as $$
  select coalesce(array_agg(m.id), '{}') from makleri m
   where m.aktivny and m.kancelaria_id in (select _kontakty_kancelarie(p_okres)) and (m.rola = 'admin' or 'odhady' = any(m.pristup))
$$;
-- skrytá kancelária, ak sa v okrese kontakty predávajú a niekto ich kupuje
create or replace function public._kontakty_trh_pre(p_okres text) returns bigint
language sql stable security definer set search_path = public as $$
  select n.kancelaria_trh from kontakty_nastavenie n
   where n.id = 1 and n.kancelaria_trh is not null and p_okres = any(n.okresy) and exists (select 1 from _kontakty_kancelarie(p_okres))
$$;
create or replace function public._kontakty_kredit(p_k bigint) returns numeric
language sql stable security definer set search_path = public as $$
  select coalesce(sum(suma), 0) from kontakty_pohyby where kancelaria_id = p_k
$$;
-- koľko kontaktov zadarmo kancelárii ešte zostáva (uznaná reklamácia kontaktu zadarmo ho vráti)
create or replace function public._kontakty_zadarmo(p_k bigint) returns integer
language sql stable security definer set search_path = public as $$
  select greatest(0, coalesce((select zadarmo from kontakty_nastavenie where id = 1), 0)
    - coalesce((select sum(case druh when 'nakup' then 1 when 'vratenie' then -1 else 0 end) from kontakty_pohyby
                 where kancelaria_id = p_k and zadarmo), 0))::int
$$;
create or replace function public._kontakty_zaloha() returns uuid
language sql stable security definer set search_path = public as $$
  select coalesce(
    (select m.id from kontakty_nastavenie n join makleri m on m.id = n.zaloha_makler and m.aktivny where n.id = 1),
    (select m.id from hlavni_spravcovia h join makleri m on m.id = h.user_id where m.aktivny order by h.vytvorene limit 1))
$$;

-- text kontaktu pre makléra (rovnaký ako pri žiadosti, ktorá ide maklérovi hneď – odhad_ziadost)
create or replace function public._odhad_kontakt_text(o public.odhady_hodnoty) returns text
language sql stable set search_path = public as $$
  select concat_ws('. ', 'Odhad hodnoty: ' || o.nazov,
                   concat_ws(', ', o.ulica || coalesce(' ' || o.cislo, ''), o.cast_obce), o.stav_nehn, _odhad_rek_text(o.rekonstrukcia),
                   case when cardinality(o.siete) > 0 then 'Siete: ' || array_to_string(o.siete, ', ') end,
                   case when cardinality(o.doplnky) > 0 then array_to_string(o.doplnky, ', ') end,
                   'Dôvod: ' || o.dovod, case when o.kedy_predat is not null then 'Predať: ' || lower(o.kedy_predat) end,
                   case when o.kedy_volat is not null then 'Volať: ' || lower(o.kedy_volat) end, 'E-mail: ' || o.email, o.poznamka,
                   case when o.auto is not null then _odhad_text(o.auto) end)
$$;

-- oznámenie do mobilov: nový kontakt a každé zlacnenie (len 7:00 – 21:00; nočné sa pošle ráno)
create or replace function public._kontakt_oznam(p_id bigint) returns integer
language plpgsql security definer set search_path = public as $$
declare
  o odhady_hodnoty;
  v_c int;
  v_hod int := extract(hour from now() at time zone 'Europe/Bratislava');
begin
  select * into o from odhady_hodnoty where id = p_id;
  if o.trh_od is null or o.predane is not null or now() >= o.trh_koniec then return 0; end if;
  if v_hod < 7 or v_hod >= 21 then return 0; end if;
  v_c := _kontakt_cena(o.trh_ceny, o.trh_od);
  if o.trh_oznamena is not null and v_c >= o.trh_oznamena then return 0; end if;
  update odhady_hodnoty set trh_oznamena = v_c where id = o.id;
  return _push_zaradit(_kontakty_kupci(o.okres), 'kontakty',
    case when o.trh_oznamena is null then '💰 Nový kontakt na predaj · ' || v_c || ' €' else '💰 Kontakt zlacnel na ' || v_c || ' €' end,
    coalesce(o.nazov, o.obec) || '. ' || coalesce(o.dovod || '. ', '') || 'Kontakt dostane prvá kancelária, ktorá ho prevezme.',
    './#odhady/trh', 'typek-trh-' || o.id);
end $$;

-- odovzdanie kontaktu maklérovi (prevzatie kanceláriou alebo záložnému maklérovi): kontakt z webu, adresár predávajúcich, zvonček
create or replace function public._kontakt_odovzdaj(p_id bigint, p_makler uuid, p_cena integer, p_zadarmo boolean, p_ako text) returns void
language plpgsql security definer set search_path = public as $$
declare
  o odhady_hodnoty;
  v_k bigint;
  v_wk bigint;
  v_prip bigint;
begin
  select * into o from odhady_hodnoty where id = p_id;
  select kancelaria_id into v_k from makleri where id = p_makler and aktivny;
  if v_k is null then raise exception 'Maklér nie je aktívny.' using errcode = '22023'; end if;

  insert into web_kontakty (web_id, makler_id, zdroj, meno, kontakt, co, odkial, portal)
  values (null, p_makler, 'odhad', o.meno, o.telefon, left(_odhad_kontakt_text(o), 1500), o.odtlacok, true)
  returning id into v_wk;

  perform set_config('typek.trh', 'ano', true);
  update odhady_hodnoty set kancelaria_id = v_k, makler_id = p_makler, web_kontakt_id = v_wk, upravene = now(),
         predane = now(), predane_cena = p_cena, predane_zadarmo = p_zadarmo, predane_kancelaria = v_k, predane_kto = p_makler, predane_ako = p_ako
   where id = o.id;
  perform set_config('typek.trh', '', true);

  if o.telefon ~ '^0\d{8,10}$' then
    insert into predajcovia (telefon, meno, poznamka, makler_id, upravene)
    values (o.telefon, o.meno, left('Odhad hodnoty (realitnytypek.sk/odhad): ' || coalesce(o.nazov, o.obec) || '. Dôvod: ' || coalesce(o.dovod, '') || coalesce('. ' || o.poznamka, ''), 2000), p_makler, now())
    on conflict (telefon, kancelaria_id) do update set
      makler_id = coalesce(predajcovia.makler_id, excluded.makler_id),
      meno = coalesce(predajcovia.meno, excluded.meno),
      poznamka = left(coalesce(predajcovia.poznamka || E'\n', '') || excluded.poznamka, 2000),
      upravene = now();
  end if;

  insert into pripomienky (makler_id, cas, poznamka, druh, web_kontakt_id)
  values (p_makler, now(), left(case when p_ako = 'nakup' then 'Prevzatý kontakt – odhad hodnoty – ' else 'Neprevzatý kontakt – odhad hodnoty – ' end ||
          coalesce(o.nazov, o.obec) || ': ' || o.meno || ', ' || coalesce(o.telefon, '') || '. ' || coalesce(o.dovod, '') ||
          case when o.dovod like 'Vyporiadanie%' then ' (spoplatnené – povedz klientovi cenu vopred)' else '' end || '.' ||
          case when o.kedy_predat is not null then ' Predať: ' || lower(o.kedy_predat) || '.' else '' end ||
          case when o.kedy_volat is not null then ' Volať: ' || lower(o.kedy_volat) || '.' else '' end, 500), 'web', v_wk)
  returning id into v_prip;
  if p_ako = 'nakup' then
    -- kupujúci je práve v aplikácii – do mobilu netreba, zvonček a pripomenutie po 2 h ostávajú
    delete from push_fronta where odoslane is null and tag = 'typek-kontakt-' || v_prip;
  else
    update push_fronta set titul = '📈 Kontakt na predaj nikto neprevzal – je tvoj', url = './#odhady/' || o.id
     where odoslane is null and tag = 'typek-kontakt-' || v_prip;
  end if;
  -- čakajúce oznámenia „kontakt na predaj“ ostatným už netreba
  delete from push_fronta where odoslane is null and tag = 'typek-trh-' || o.id;
end $$;

-- ---------------------------------------------------------------- žiadosť o odhad (115 + predaj kontaktov)
create or replace function public.odhad_ziadost(p_udaje jsonb, p_overenie jsonb default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  STAVY constant text[] := array['Novostavba', 'Po kompletnej rekonštrukcii', 'Čiastočne zrekonštruovaný', 'Pôvodný, udržiavaný', 'Na rekonštrukciu'];
  DOVODY constant text[] := array['Zvažujem predaj', 'Mám záujem aj o ponuku na výkup', 'Len informatívne, zaujíma ma hodnota',
                                  'Vyporiadanie BSM, rozvod alebo delenie majetku', 'Iný dôvod'];
  DRUHY constant text[] := array['Stavebný', 'Záhrada', 'Orná pôda alebo lúka', 'Iný alebo neviem'];
  SIETE constant text[] := array['Elektrina', 'Voda', 'Kanalizácia', 'Plyn', 'Žiadne siete', 'Neviem'];
  DOPLNKY constant text[] := array['Balkón alebo loggia', 'Pivnica', 'Výťah', 'Garáž alebo parkovanie', 'Zateplený dom', 'Garáž', 'Terasa',
                                   'Zateplenie', 'Nové kúrenie', 'Prístup po spevnenej ceste', 'Rovinatý', 'Vydané stavebné povolenie'];
  v_typ text := case when p_udaje->>'typ' in ('byt', 'dom', 'pozemok', 'ine') then p_udaje->>'typ' end;
  v_obec text := _odhad_txt(p_udaje->>'obec', 60);
  v_okres text := _odhad_txt(p_udaje->>'okres', 60);
  v_kraj text; v_cast text := _odhad_txt(p_udaje->>'cast_obce', 60);
  v_ulica text := _odhad_txt(p_udaje->>'ulica', 80);
  v_cislo text := _odhad_txt(p_udaje->>'cislo', 15);
  v_plocha numeric; v_pozemok numeric; v_izby text; v_posch integer; v_posch_sp integer;
  v_druh text; v_popis text := _odhad_txt(p_udaje->>'popis', 120);
  v_stav text := _odhad_txt(p_udaje->>'stav', 40);
  v_rek jsonb;
  v_siete text[]; v_doplnky text[];
  v_dovod text := _odhad_txt(p_udaje->>'dovod', 80);
  v_pozn text := nullif(left(btrim(coalesce(p_udaje->>'poznamka', '')), 1000), '');
  v_kedy text := case when p_udaje->>'kedy_predat' in ('Čo najskôr', 'Do 3 mesiacov', 'Do roka', 'Zatiaľ len zisťujem') then p_udaje->>'kedy_predat' end;
  v_volat text := case when p_udaje->>'kedy_volat' in ('Doobeda', 'Poobede', 'Kedykoľvek', 'Radšej e-mailom') then p_udaje->>'kedy_volat' end;
  v_fotky int := case when coalesce(p_udaje->>'fotky', '') ~ '^[0-9]{1,2}$' then least((p_udaje->>'fotky')::int, 6) else 0 end;
  v_tok text; v_cesta text;
  v_meno text := _odhad_txt(p_udaje->>'meno', 80);
  v_tel text := _odhad_txt(p_udaje->>'telefon', 25);
  v_email text := lower(_odhad_txt(p_udaje->>'email', 120));
  v_odkial text := _odhad_txt(p_udaje->>'odkial', 300);
  v_odtlacok text := _klient_odtlacok();
  v_hodina int; v_komu uuid; v_auto jsonb; v_nazov text; v_kontakt_id bigint; v_id bigint; v_prip bigint; v_text text;
  v_trh bigint; v_start timestamptz; n kontakty_nastavenie;
begin
  -- pasca na roboty: skryté pole vyplní len robot → tváriť sa ako úspech, nič neuložiť
  if coalesce(p_overenie->>'med', '') <> '' then return jsonb_build_object('ok', true); end if;
  select count(*) into v_hodina from odhady_hodnoty where vytvorene > now() - interval '1 hour';
  if v_hodina >= 200 then raise exception 'Príliš veľa žiadostí naraz. Skúste to o chvíľu.' using errcode = '54000'; end if;
  perform _portal_overenie2('odhad', 'odhad', p_overenie, case when v_hodina >= 20 then 5 else 4 end);

  if v_typ is null then raise exception 'Vyberte, čo chcete oceniť.' using errcode = '22023'; end if;
  -- obec zo zoznamu obcí a mestských častí SR
  if v_obec is null then raise exception 'Vyberte obec.' using errcode = '22023'; end if;
  select l.nazov, l.okres, l.kraj into v_obec, v_okres, v_kraj from lokality l
   where l.typ in ('obec', 'cast') and _bez_diakritiky(l.nazov) = _bez_diakritiky(v_obec)
   order by (l.okres = v_okres) is true desc, (l.nazov = v_obec) desc, l.mesto desc nulls last limit 1;
  if not found then raise exception 'Vyberte obec zo zoznamu.' using errcode = '22023'; end if;
  if v_typ in ('byt', 'dom') and v_ulica is null then raise exception 'Napíšte ulicu.' using errcode = '22023'; end if;

  -- veľkosť
  if v_typ = 'byt' then
    v_plocha := _odhad_cislo(p_udaje->>'plocha', 10, 1000);
    if v_plocha is null then raise exception 'Napíšte výmeru bytu (10 – 1 000 m²).' using errcode = '22023'; end if;
    v_izby := case when p_udaje->>'izby' in ('1', '2', '3', '4', '5 a viac') then p_udaje->>'izby' end;
    if v_izby is null then raise exception 'Vyberte počet izieb.' using errcode = '22023'; end if;
    v_posch := _odhad_cislo(p_udaje->>'poschodie', -1, 30)::integer;
    if v_posch is null then raise exception 'Napíšte poschodie (prízemie = 0).' using errcode = '22023'; end if;
    v_posch_sp := _odhad_cislo(p_udaje->>'poschodi', 1, 30)::integer;
    if v_posch_sp is not null and v_posch_sp < v_posch then raise exception 'Poschodie nemôže byť vyššie ako počet poschodí domu.' using errcode = '22023'; end if;
  elsif v_typ = 'dom' then
    v_plocha := _odhad_cislo(p_udaje->>'plocha', 20, 3000);
    if v_plocha is null then raise exception 'Napíšte úžitkovú plochu domu (20 – 3 000 m²).' using errcode = '22023'; end if;
    v_pozemok := _odhad_cislo(p_udaje->>'pozemok', 0, 200000);
    v_izby := case when p_udaje->>'izby' in ('2 a menej', '3', '4', '5', '6 a viac') then p_udaje->>'izby' end;
    if v_izby is null then raise exception 'Vyberte počet izieb.' using errcode = '22023'; end if;
  elsif v_typ = 'pozemok' then
    v_plocha := _odhad_cislo(p_udaje->>'plocha', 10, 10000000);
    if v_plocha is null then raise exception 'Napíšte výmeru pozemku v m².' using errcode = '22023'; end if;
    v_druh := case when p_udaje->>'druh_pozemku' = any(DRUHY) then p_udaje->>'druh_pozemku' end;
    if v_druh is null then raise exception 'Vyberte druh pozemku.' using errcode = '22023'; end if;
  else
    if v_popis is null then raise exception 'Napíšte, čo chcete oceniť.' using errcode = '22023'; end if;
    v_plocha := _odhad_cislo(p_udaje->>'plocha', 1, 100000);
  end if;

  -- stav, siete, doplnky
  if v_typ = 'pozemok' then
    select coalesce(array_agg(distinct x), '{}') into v_siete from jsonb_array_elements_text(case when jsonb_typeof(p_udaje->'siete') = 'array' then p_udaje->'siete' else '[]' end) x where x = any(SIETE);
    if cardinality(v_siete) = 0 then raise exception 'Vyberte siete na pozemku (alebo „Neviem“).' using errcode = '22023'; end if;
    v_stav := null;
  else
    if not (v_stav = any(STAVY)) then raise exception 'Vyberte stav nehnuteľnosti.' using errcode = '22023'; end if;
    v_siete := '{}';
    -- byt: čo je prerobené a kedy (pri novostavbe a „na rekonštrukciu“ sa nepýtame)
    if v_typ = 'byt' and v_stav in ('Po kompletnej rekonštrukcii', 'Čiastočne zrekonštruovaný', 'Pôvodný, udržiavaný') then
      v_rek := _odhad_rek(p_udaje->'rekonstrukcia');
    end if;
  end if;
  select coalesce(array_agg(distinct x), '{}') into v_doplnky from jsonb_array_elements_text(case when jsonb_typeof(p_udaje->'doplnky') = 'array' then p_udaje->'doplnky' else '[]' end) x where x = any(DOPLNKY);
  if not (v_dovod = any(DOVODY)) then raise exception 'Vyberte, prečo chcete odhad.' using errcode = '22023'; end if;

  -- kontakt
  if v_meno is null or length(v_meno) < 2 then raise exception 'Napíšte svoje meno.' using errcode = '22023'; end if;
  v_tel := coalesce(_tel_norm(v_tel), case when regexp_replace(coalesce(v_tel, ''), '[\s/.-]', '', 'g') ~ '^\+\d{9,15}$' then regexp_replace(v_tel, '[\s/.-]', '', 'g') end);
  if v_tel is null then raise exception 'Skontrolujte telefónne číslo.' using errcode = '22023'; end if;
  if v_email is null or v_email !~ '^[a-z0-9._%+-]+@[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)*\.[a-z]{2,}$' then
    raise exception 'Skontrolujte e-mailovú adresu.' using errcode = '22023';
  end if;

  -- z jedného miesta najviac 5 žiadostí za hodinu; dvojklik / opakované odoslanie tej istej žiadosti sa neuloží druhýkrát
  perform pg_advisory_xact_lock(918277, hashtext(coalesce(v_odtlacok, v_email)));
  if v_odtlacok is not null and (select count(*) from odhady_hodnoty where odtlacok = v_odtlacok and vytvorene > now() - interval '1 hour') >= 5 then
    raise exception 'Príliš veľa žiadostí naraz. Skúste to o chvíľu.' using errcode = '54000';
  end if;
  select id, makler_id into v_id, v_komu from odhady_hodnoty
   where email = v_email and typ = v_typ and obec = v_obec and coalesce(ulica, '') = coalesce(v_ulica, '') and vytvorene > now() - interval '15 minutes'
   order by id desc limit 1;

  if v_id is null then
    if v_typ in ('byt', 'dom', 'pozemok') then v_auto := _odhad_ceny(v_typ, v_obec, v_plocha); end if;
    v_nazov := _odhad_nazov(v_typ, v_izby, v_druh, v_popis, v_plocha, v_pozemok, v_obec, v_okres);
    v_trh := _kontakty_trh_pre(v_okres);

    if v_trh is not null then
      -- kontakt na predaj (117): žiadosť zatiaľ nikto nevidí, kancelárie s okresom dostanú náhľad bez osobných údajov
      select * into n from kontakty_nastavenie where id = 1;
      v_start := _kontakt_start(now());
      perform set_config('typek.trh', 'ano', true);
      insert into odhady_hodnoty (kancelaria_id, makler_id, web_kontakt_id, typ, nazov, kraj, okres, obec, cast_obce, ulica, cislo, plocha, pozemok, izby, poschodie, poschodi,
                          druh_pozemku, popis, stav_nehn, siete, doplnky, dovod, poznamka, meno, telefon, email, odkial, odtlacok, auto, potvrdenie_poslat,
                          kedy_predat, kedy_volat, rekonstrukcia, trh_od, trh_koniec, trh_ceny)
      values (v_trh, null, null, v_typ, v_nazov, v_kraj, v_okres, v_obec, v_cast, v_ulica, v_cislo, v_plocha, v_pozemok, v_izby, v_posch, v_posch_sp,
              v_druh, case when v_typ = 'ine' then v_popis end, v_stav, v_siete, v_doplnky, v_dovod, v_pozn, v_meno, v_tel, v_email, v_odkial, v_odtlacok, v_auto, true,
              v_kedy, v_volat, v_rek, v_start, v_start + n.koniec_h * interval '1 hour', n.ceny)
      returning id into v_id;
      perform _kontakt_oznam(v_id);
    else
      v_komu := _odhad_makler(v_obec, v_okres);
      if v_komu is null then raise exception 'Formulár je dočasne nedostupný. Skúste to neskôr.' using errcode = '22023'; end if;
      v_text := concat_ws('. ', 'Odhad hodnoty: ' || v_nazov,
                          concat_ws(', ', v_ulica || coalesce(' ' || v_cislo, ''), v_cast), v_stav, _odhad_rek_text(v_rek),
                          case when cardinality(v_siete) > 0 then 'Siete: ' || array_to_string(v_siete, ', ') end,
                          case when cardinality(v_doplnky) > 0 then array_to_string(v_doplnky, ', ') end,
                          'Dôvod: ' || v_dovod, case when v_kedy is not null then 'Predať: ' || lower(v_kedy) end,
                          case when v_volat is not null then 'Volať: ' || lower(v_volat) end, 'E-mail: ' || v_email, v_pozn,
                          case when v_auto is not null then _odhad_text(v_auto) end);

      insert into web_kontakty (web_id, makler_id, zdroj, meno, kontakt, co, odkial, portal)
      values (null, v_komu, 'odhad', v_meno, v_tel, left(v_text, 1500), v_odtlacok, true)
      returning id into v_kontakt_id;

      insert into odhady_hodnoty (makler_id, web_kontakt_id, typ, nazov, kraj, okres, obec, cast_obce, ulica, cislo, plocha, pozemok, izby, poschodie, poschodi,
                          druh_pozemku, popis, stav_nehn, siete, doplnky, dovod, poznamka, meno, telefon, email, odkial, odtlacok, auto, potvrdenie_poslat,
                          kedy_predat, kedy_volat, rekonstrukcia)
      values (v_komu, v_kontakt_id, v_typ, v_nazov, v_kraj, v_okres, v_obec, v_cast, v_ulica, v_cislo, v_plocha, v_pozemok, v_izby, v_posch, v_posch_sp,
              v_druh, case when v_typ = 'ine' then v_popis end, v_stav, v_siete, v_doplnky, v_dovod, v_pozn, v_meno, v_tel, v_email, v_odkial, v_odtlacok, v_auto, true,
              v_kedy, v_volat, v_rek)
      returning id into v_id;

      -- predávajúci v adresári kancelárie (ako pri „Chcem predať“ na portáli)
      if v_tel ~ '^0\d{8,10}$' then
        insert into predajcovia (telefon, meno, poznamka, makler_id, upravene)
        values (v_tel, v_meno, left('Odhad hodnoty (realitnytypek.sk/odhad): ' || v_nazov || '. Dôvod: ' || v_dovod || coalesce('. ' || v_pozn, ''), 2000), v_komu, now())
        on conflict (telefon, kancelaria_id) do update set
          makler_id = coalesce(predajcovia.makler_id, excluded.makler_id),
          meno = coalesce(predajcovia.meno, excluded.meno),
          poznamka = left(coalesce(predajcovia.poznamka || E'\n', '') || excluded.poznamka, 2000),
          upravene = now();
      end if;

      insert into pripomienky (makler_id, cas, poznamka, druh, web_kontakt_id)
      values (v_komu, now(), left('Nová žiadosť o odhad hodnoty – ' || v_nazov || ': ' || v_meno || ', ' || v_tel || '. ' || v_dovod ||
              case when v_dovod like 'Vyporiadanie%' then ' (spoplatnené – povedz klientovi cenu vopred)' else '' end || '.' ||
              case when v_kedy is not null then ' Predať: ' || lower(v_kedy) || '.' else '' end ||
              case when v_volat is not null then ' Volať: ' || lower(v_volat) || '.' else '' end, 500), 'web', v_kontakt_id)
      returning id into v_prip;
      update push_fronta set titul = case when v_kedy = 'Čo najskôr' then '🔥 Odhad hodnoty – chce predať čo najskôr'
                                          when v_dovod like '%výkup%' then '📈 Odhad hodnoty + záujem o výkup' else '📈 Nová žiadosť o odhad hodnoty' end,
                             url = './#odhady/' || v_id
       where odoslane is null and tag = 'typek-kontakt-' || v_prip;
    end if;
  end if;

  -- fotky: jednorazové povolenie nahrať najviac 6 fotiek do priečinka <id>/<kľúč>/ (platí hodinu, v databáze len odtlačok kľúča)
  if v_fotky > 0 then
    v_tok := encode(extensions.gen_random_bytes(16), 'hex');
    v_cesta := v_id || '/' || v_tok;
    update odhady_hodnoty set fotky_token_hash = encode(extensions.digest(v_tok, 'sha256'), 'hex'), fotky_do = now() + interval '1 hour', fotky_cesta = v_cesta
     where id = v_id;
  end if;

  return jsonb_build_object('ok', true, 'obec', v_obec, 'okres', v_okres,
    'fotky', case when v_tok is not null then jsonb_build_object('id', v_id, 'token', v_tok, 'cesta', v_cesta) end,
    'pokryte', coalesce((select odhad_pokrytie() ? v_okres), false));
end $$;

-- ---------------------------------------------------------------- aplikácia: kontakty na predaj pre kanceláriu
create or replace function public.kontakty_na_predaj() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v_k bigint := moja_kancelaria();
  n kontakty_nastavenie;
  v_okresy text[];
begin
  if not ja_aktivny() or not ma_pristup('odhady') then raise exception 'Nemáte prístup k odhadom.' using errcode = '42501'; end if;
  select * into n from kontakty_nastavenie where id = 1;
  select coalesce(array_agg(o order by o), '{}') into v_okresy from unnest(n.okresy) o where v_k in (select _kontakty_kancelarie(o));
  return jsonb_build_object(
    'okresy', to_jsonb(v_okresy),
    'kredit', _kontakty_kredit(v_k), 'zadarmo', _kontakty_zadarmo(v_k), 'zadarmo_spolu', n.zadarmo,
    'ceny', n.ceny, 'koniec_h', n.koniec_h, 'reklamacia_h', n.reklamacia_h,
    'ponuky', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', o.id, 'typ', o.typ, 'nazov', o.nazov, 'okres', o.okres, 'obec', o.obec, 'cast_obce', o.cast_obce,
        'plocha', o.plocha, 'pozemok', o.pozemok, 'izby', o.izby, 'poschodie', o.poschodie, 'poschodi', o.poschodi, 'druh_pozemku', o.druh_pozemku,
        'stav', o.stav_nehn, 'rek', _odhad_rek_text(o.rekonstrukcia), 'doplnky', o.doplnky, 'siete', o.siete,
        'dovod', o.dovod, 'kedy_predat', o.kedy_predat, 'kedy_volat', o.kedy_volat, 'fotky', o.fotky,
        'odhad', coalesce(case when md.m ? 'od' and md.m->>'od' is not null then jsonb_build_object('od', md.m->'od', 'do', md.m->'do', 'podla', 'median') end,
                          case when o.auto->>'od' is not null then jsonb_build_object('od', o.auto->'od', 'do', o.auto->'do', 'podla', 'skener') end),
        'vytvorene', o.vytvorene, 'od', o.trh_od, 'koniec', o.trh_koniec,
        'cena', _kontakt_cena(o.trh_ceny, o.trh_od), 'dalsia', _kontakt_dalsia(o.trh_ceny, o.trh_od)) order by o.vytvorene desc)
      from odhady_hodnoty o
      left join lateral (select case when o.typ = 'byt' then _odhad_median(o) end as m) md on true
      where o.trh_od is not null and o.predane is null and o.trh_koniec > now() and o.okres = any(v_okresy)), '[]'::jsonb),
    'kupene', coalesce((
      select jsonb_agg(jsonb_build_object('id', o.id, 'nazov', o.nazov, 'predane', o.predane, 'cena', o.predane_cena, 'zadarmo', o.predane_zadarmo,
        'kto', o.predane_kto, 'reklamacia', (select jsonb_build_object('stav', r.stav, 'dovod', r.dovod, 'odpoved', r.odpoved) from kontakty_reklamacie r where r.odhad_id = o.id))
        order by o.predane desc)
      from odhady_hodnoty o where o.predane_kancelaria = v_k and o.predane_ako = 'nakup' and o.predane > now() - interval '90 days'), '[]'::jsonb),
    'pohyby', case when ja_admin() then coalesce((
      select jsonb_agg(to_jsonb(x) order by x.id desc) from (
        select id, vytvorene, druh, suma, zadarmo, poznamka from kontakty_pohyby where kancelaria_id = v_k order by id desc limit 30) x), '[]'::jsonb) end);
end $$;

-- prevzatie kontaktu: kto prvý klikne, platí aktuálnu cenu (prvé kontakty zadarmo, potom z kreditu)
create or replace function public.kontakt_prevziat(p_id bigint, p_cena integer default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_ja uuid := auth.uid();
  v_k bigint := moja_kancelaria();
  o odhady_hodnoty;
  v_cena int;
  v_zadarmo boolean;
  v_kredit numeric;
begin
  if v_ja is null or not ja_aktivny() or not ma_pristup('odhady') then raise exception 'Nemáte prístup k odhadom.' using errcode = '42501'; end if;
  if aktivna_kancelaria() is distinct from v_k then raise exception 'Kontakt sa dá prevziať len vo vlastnej kancelárii.' using errcode = '42501'; end if;
  perform pg_advisory_xact_lock(918278, v_k::int);
  select * into o from odhady_hodnoty where id = p_id for update;
  if not found or o.trh_od is null then raise exception 'Kontakt sa nenašiel.' using errcode = '22023'; end if;
  if o.predane is not null then
    raise exception '%', case when o.predane_kancelaria = v_k then 'Tento kontakt už vaša kancelária má.' else 'Tento kontakt už prevzala iná kancelária.' end using errcode = '22023';
  end if;
  if now() >= o.trh_koniec then raise exception 'Ponuka tohto kontaktu už skončila.' using errcode = '22023'; end if;
  if not (v_k in (select _kontakty_kancelarie(o.okres))) then
    raise exception 'Vaša kancelária kontakty z okresu % neprevezme – okres nie je medzi vašimi.', o.okres using errcode = '42501';
  end if;
  v_cena := _kontakt_cena(o.trh_ceny, o.trh_od);
  if p_cena is not null and v_cena > p_cena then
    raise exception 'Cena sa medzitým zmenila na % €. Skúste to znova.', v_cena using errcode = '22023';
  end if;
  v_zadarmo := _kontakty_zadarmo(v_k) > 0;
  if not v_zadarmo then
    v_kredit := _kontakty_kredit(v_k);
    if v_kredit < v_cena then
      raise exception 'Nemáte dosť kreditu: zostatok % €, kontakt stojí % €. Kredit vám pripíšeme po platbe – napíšte na info@realitnytypek.sk.',
        trim(to_char(v_kredit, 'FM999990.00')), v_cena using errcode = '22023';
    end if;
  end if;
  insert into kontakty_pohyby (kancelaria_id, druh, suma, zadarmo, odhad_id, kto, poznamka)
  values (v_k, 'nakup', case when v_zadarmo then 0 else -v_cena end, v_zadarmo, o.id, v_ja,
          left(coalesce(o.nazov, o.obec) || case when v_zadarmo then ' (zadarmo)' else '' end, 200));
  perform _kontakt_odovzdaj(o.id, v_ja, case when v_zadarmo then 0 else v_cena end, v_zadarmo, 'nakup');
  return jsonb_build_object('ok', true, 'id', o.id, 'cena', case when v_zadarmo then 0 else v_cena end, 'zadarmo', v_zadarmo,
    'kredit', _kontakty_kredit(v_k), 'zostava_zadarmo', _kontakty_zadarmo(v_k));
end $$;

-- reklamácia do 48 h od prevzatia
create or replace function public.kontakt_reklamovat(p_id bigint, p_dovod text, p_text text default null) returns void
language plpgsql security definer set search_path = public as $$
declare
  DOVODY constant text[] := array['Nesprávne telefónne číslo a e-mail', 'Klient o odhad nežiadal', 'Kontakt už sme mali (duplicitný)',
                                  'Klient nechce predávať ani poznať cenu', 'Iný dôvod'];
  o odhady_hodnoty;
  v_h int := (select reklamacia_h from kontakty_nastavenie where id = 1);
  v_text text := nullif(left(btrim(coalesce(p_text, '')), 1000), '');
begin
  if not ja_aktivny() then raise exception 'Účet nie je aktívny.' using errcode = '42501'; end if;
  select * into o from odhady_hodnoty where id = p_id and predane_ako = 'nakup' and predane_kancelaria = moja_kancelaria();
  if not found then raise exception 'Kontakt nepatrí vašej kancelárii.' using errcode = '42501'; end if;
  if not (ja_admin() or o.predane_kto = auth.uid() or o.makler_id = auth.uid()) then
    raise exception 'Reklamovať môže maklér, ktorý kontakt prevzal, alebo administrátor.' using errcode = '42501';
  end if;
  if now() > o.predane + v_h * interval '1 hour' then raise exception 'Reklamovať sa dá do % hodín od prevzatia.', v_h using errcode = '22023'; end if;
  if exists (select 1 from kontakty_reklamacie where odhad_id = o.id) then raise exception 'Kontakt už je reklamovaný.' using errcode = '22023'; end if;
  if not (p_dovod = any(DOVODY)) then raise exception 'Vyberte dôvod reklamácie.' using errcode = '22023'; end if;
  if p_dovod = 'Iný dôvod' and v_text is null then raise exception 'Napíšte, prečo kontakt reklamujete.' using errcode = '22023'; end if;
  insert into kontakty_reklamacie (odhad_id, kancelaria_id, kto, dovod, text) values (o.id, o.predane_kancelaria, auth.uid(), p_dovod, v_text);
  perform _push_zaradit(array(select user_id from hlavni_spravcovia), 'kontakty', '⚠️ Reklamácia kontaktu · ' || coalesce(o.predane_cena, 0) || ' €',
    coalesce(o.nazov, o.obec) || ' – ' || p_dovod || coalesce(': ' || v_text, ''), './sprava.html#kontakty', 'typek-rekl-' || o.id);
end $$;

-- ---------------------------------------------------------------- Správa zákazníkov (hlavný správca)
create or replace function public.kontakty_sprava() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare n kontakty_nastavenie;
begin
  if not je_hlavny_spravca() then raise exception 'Len pre hlavného správcu.' using errcode = '42501'; end if;
  select * into n from kontakty_nastavenie where id = 1;
  return jsonb_build_object(
    'nastavenie', jsonb_build_object('okresy', n.okresy, 'ceny', n.ceny, 'koniec_h', n.koniec_h, 'zadarmo', n.zadarmo,
                                     'reklamacia_h', n.reklamacia_h, 'zaloha_makler', n.zaloha_makler, 'upravene', n.upravene),
    'zaloha', (select jsonb_build_object('id', m.id, 'meno', m.meno) from makleri m where m.id = _kontakty_zaloha()),
    'zalohy', coalesce((select jsonb_agg(jsonb_build_object('id', m.id, 'meno', m.meno) order by m.meno)
                          from makleri m where m.aktivny and m.kancelaria_id = moja_kancelaria()), '[]'::jsonb),
    'vsetky_okresy', coalesce((select jsonb_agg(o order by o) from (select distinct okres o from lokality where typ = 'obec' and okres is not null) x), '[]'::jsonb),
    'pokrytie', coalesce((select jsonb_object_agg(o, (select count(*) from _kontakty_kancelarie(o))) from (select distinct unnest(k.okresy) o from kancelarie k where k.aktivna) x), '{}'::jsonb),
    'kancelarie', coalesce((select jsonb_agg(jsonb_build_object('id', k.id, 'nazov', k.nazov, 'okresy', k.okresy, 'aktivna', k.aktivna,
        'kredit', _kontakty_kredit(k.id), 'zadarmo', _kontakty_zadarmo(k.id),
        'kupene', (select count(*) from kontakty_pohyby p where p.kancelaria_id = k.id and p.druh = 'nakup'),
        'zaplatene', (select coalesce(-sum(p.suma), 0) from kontakty_pohyby p where p.kancelaria_id = k.id and p.druh in ('nakup', 'vratenie')),
        'dobite', (select coalesce(sum(p.suma), 0) from kontakty_pohyby p where p.kancelaria_id = k.id and p.druh = 'dobitie')) order by k.nazov)
      from kancelarie k where k.id is distinct from n.kancelaria_trh), '[]'::jsonb),
    'trh', coalesce((select jsonb_agg(jsonb_build_object('id', o.id, 'nazov', o.nazov, 'okres', o.okres, 'dovod', o.dovod, 'vytvorene', o.vytvorene,
        'od', o.trh_od, 'koniec', o.trh_koniec, 'cena', case when o.predane is null then _kontakt_cena(o.trh_ceny, o.trh_od) end,
        'dalsia', case when o.predane is null then _kontakt_dalsia(o.trh_ceny, o.trh_od) end,
        'predane', o.predane, 'predane_cena', o.predane_cena, 'zadarmo', o.predane_zadarmo, 'ako', o.predane_ako,
        'kancelaria', (select k.nazov from kancelarie k where k.id = o.predane_kancelaria), 'kto', (select m.meno from makleri m where m.id = o.predane_kto),
        'kupci', (select count(*) from _kontakty_kancelarie(o.okres)),
        'reklamacia', (select r.stav from kontakty_reklamacie r where r.odhad_id = o.id)) order by o.vytvorene desc)
      from odhady_hodnoty o where o.trh_od is not null and (o.predane is null or o.predane > now() - interval '60 days')), '[]'::jsonb),
    'reklamacie', coalesce((select jsonb_agg(jsonb_build_object('id', r.id, 'odhad_id', r.odhad_id, 'nazov', o.nazov, 'cena', o.predane_cena, 'zadarmo', o.predane_zadarmo,
        'predane', o.predane, 'kancelaria', (select k.nazov from kancelarie k where k.id = r.kancelaria_id), 'kto', (select m.meno from makleri m where m.id = r.kto),
        'dovod', r.dovod, 'text', r.text, 'vytvorene', r.vytvorene, 'stav', r.stav, 'vybavene', r.vybavene, 'odpoved', r.odpoved,
        'telefon', o.telefon, 'email', o.email, 'meno', o.meno) order by (r.stav = 'caka') desc, r.vytvorene desc)
      from kontakty_reklamacie r left join odhady_hodnoty o on o.id = r.odhad_id where r.stav = 'caka' or r.vytvorene > now() - interval '90 days'), '[]'::jsonb),
    'pohyby', coalesce((select jsonb_agg(jsonb_build_object('id', p.id, 'vytvorene', p.vytvorene, 'druh', p.druh, 'suma', p.suma, 'zadarmo', p.zadarmo,
        'poznamka', p.poznamka, 'kancelaria', (select k.nazov from kancelarie k where k.id = p.kancelaria_id), 'kto', (select m.meno from makleri m where m.id = p.kto)) order by p.id desc)
      from (select * from kontakty_pohyby order by id desc limit 100) p), '[]'::jsonb));
end $$;

create or replace function public.kontakty_nastavit(p jsonb) returns void
language plpgsql security definer set search_path = public as $$
declare
  v_okresy text[];
  v_ceny jsonb;
  v_h float8 := -1; v_c int := 100000; e jsonb;
  v_koniec int := (p->>'koniec_h')::int;
  v_zadarmo int := (p->>'zadarmo')::int;
  v_rekl int := (p->>'reklamacia_h')::int;
  v_zaloha uuid := nullif(p->>'zaloha_makler', '')::uuid;
begin
  if not je_hlavny_spravca() then raise exception 'Len pre hlavného správcu.' using errcode = '42501'; end if;
  select coalesce(array_agg(distinct x order by x), '{}') into v_okresy
    from jsonb_array_elements_text(case when jsonb_typeof(p->'okresy') = 'array' then p->'okresy' else '[]' end) x;
  if exists (select 1 from unnest(v_okresy) x where not exists (select 1 from lokality l where l.typ = 'obec' and l.okres = x)) then
    raise exception 'Neznámy okres.' using errcode = '22023';
  end if;
  v_ceny := p->'ceny';
  if jsonb_typeof(v_ceny) <> 'array' or jsonb_array_length(v_ceny) not between 1 and 8 then raise exception 'Zadajte 1 až 8 cien.' using errcode = '22023'; end if;
  for e in select x from jsonb_array_elements(v_ceny) x loop
    if coalesce(e->>'h', '') !~ '^\d{1,3}(\.\d+)?$' or coalesce(e->>'c', '') !~ '^\d{1,3}$' then raise exception 'Cena musí byť celé číslo a čas v hodinách.' using errcode = '22023'; end if;
    if v_h < 0 and (e->>'h')::float8 <> 0 then raise exception 'Prvá cena musí platiť od 0 hodín.' using errcode = '22023'; end if;
    if (e->>'h')::float8 <= v_h then raise exception 'Časy cien musia ísť za sebou (0, 4, 12…).' using errcode = '22023'; end if;
    if (e->>'c')::int < 1 or (e->>'c')::int > 500 then raise exception 'Cena musí byť od 1 do 500 €.' using errcode = '22023'; end if;
    if (e->>'c')::int > v_c then raise exception 'Cena môže časom len klesať.' using errcode = '22023'; end if;
    v_h := (e->>'h')::float8; v_c := (e->>'c')::int;
  end loop;
  v_ceny := (select jsonb_agg(jsonb_build_object('h', (x->>'h')::numeric, 'c', (x->>'c')::int)) from jsonb_array_elements(v_ceny) x);
  if v_koniec is null or v_koniec not between 1 and 336 or v_koniec <= v_h then
    raise exception 'Odovzdanie záložnému maklérovi musí byť neskôr ako posledné zlacnenie (najviac 336 h).' using errcode = '22023';
  end if;
  if v_zadarmo is null or v_zadarmo not between 0 and 20 then raise exception 'Kontaktov zadarmo môže byť 0 až 20.' using errcode = '22023'; end if;
  if v_rekl is null or v_rekl not between 1 and 336 then raise exception 'Lehota na reklamáciu musí byť 1 až 336 hodín.' using errcode = '22023'; end if;
  if v_zaloha is not null and not exists (select 1 from makleri where id = v_zaloha and aktivny and kancelaria_id = moja_kancelaria()) then
    raise exception 'Záložný maklér musí byť aktívny maklér vašej kancelárie.' using errcode = '22023';
  end if;
  update kontakty_nastavenie set okresy = v_okresy, ceny = v_ceny, koniec_h = v_koniec, zadarmo = v_zadarmo, reklamacia_h = v_rekl,
         zaloha_makler = v_zaloha, upravene = now()
   where id = 1;
end $$;

-- pripísanie kreditu po platbe (alebo oprava so znamienkom mínus)
create or replace function public.kontakty_dobit(p_kancelaria bigint, p_suma numeric, p_poznamka text default null) returns numeric
language plpgsql security definer set search_path = public as $$
begin
  if not je_hlavny_spravca() then raise exception 'Len pre hlavného správcu.' using errcode = '42501'; end if;
  if not exists (select 1 from kancelarie where id = p_kancelaria) or p_kancelaria = (select kancelaria_trh from kontakty_nastavenie where id = 1) then
    raise exception 'Kancelária neexistuje.' using errcode = '22023';
  end if;
  if p_suma is null or p_suma = 0 or abs(p_suma) > 10000 or p_suma <> round(p_suma, 2) then raise exception 'Zadajte sumu (najviac 10 000 €).' using errcode = '22023'; end if;
  insert into kontakty_pohyby (kancelaria_id, druh, suma, kto, poznamka)
  values (p_kancelaria, case when p_suma > 0 then 'dobitie' else 'oprava' end, p_suma, auth.uid(), nullif(left(btrim(coalesce(p_poznamka, '')), 200), ''));
  return _kontakty_kredit(p_kancelaria);
end $$;

-- reklamácia: uznať (kredit alebo kontakt zadarmo sa vráti) alebo zamietnuť; maklér dostane upozornenie
create or replace function public.kontakt_reklamacia_vybav(p_id bigint, p_uznat boolean, p_odpoved text default null) returns void
language plpgsql security definer set search_path = public as $$
declare
  r kontakty_reklamacie;
  o odhady_hodnoty;
  v_odp text := nullif(left(btrim(coalesce(p_odpoved, '')), 1000), '');
begin
  if not je_hlavny_spravca() then raise exception 'Len pre hlavného správcu.' using errcode = '42501'; end if;
  select * into r from kontakty_reklamacie where id = p_id for update;
  if not found then raise exception 'Reklamácia sa nenašla.' using errcode = '22023'; end if;
  if r.stav <> 'caka' then raise exception 'Reklamácia už je vybavená.' using errcode = '22023'; end if;
  if not p_uznat and v_odp is null then raise exception 'Pri zamietnutí napíšte dôvod.' using errcode = '22023'; end if;
  select * into o from odhady_hodnoty where id = r.odhad_id;
  update kontakty_reklamacie set stav = case when p_uznat then 'uznana' else 'zamietnuta' end, vybavene = now(), vybavil = auth.uid(), odpoved = v_odp where id = r.id;
  if p_uznat then
    insert into kontakty_pohyby (kancelaria_id, druh, suma, zadarmo, odhad_id, kto, poznamka)
    values (r.kancelaria_id, 'vratenie', coalesce(o.predane_cena, 0), coalesce(o.predane_zadarmo, false), r.odhad_id, auth.uid(),
            left('Uznaná reklamácia: ' || coalesce(o.nazov, '') , 200));
  end if;
  perform _push_zaradit(array[r.kto], 'kontakty',
    case when p_uznat then '✅ Reklamácia uznaná' || case when coalesce(o.predane_cena, 0) > 0 then ' · ' || o.predane_cena || ' € späť' else ' · kontakt zadarmo späť' end
         else '✖️ Reklamácia zamietnutá' end,
    coalesce(o.nazov, 'Kontakt') || coalesce(' – ' || v_odp, ''), './#odhady/' || r.odhad_id, 'typek-rekl-' || r.odhad_id);
end $$;

-- kontakt, ktorý nikto neprevzal, hneď záložnému maklérovi (napr. pri skúšaní alebo keď klient volal priamo)
create or replace function public.kontakt_odovzdat_zalohe(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare o odhady_hodnoty; v_z uuid := _kontakty_zaloha();
begin
  if not je_hlavny_spravca() then raise exception 'Len pre hlavného správcu.' using errcode = '42501'; end if;
  select * into o from odhady_hodnoty where id = p_id for update;
  if not found or o.trh_od is null or o.predane is not null then raise exception 'Kontakt už nie je na predaj.' using errcode = '22023'; end if;
  if v_z is null then raise exception 'Nie je nastavený záložný maklér.' using errcode = '22023'; end if;
  perform _kontakt_odovzdaj(o.id, v_z, 0, false, 'zaloha');
end $$;

-- ---------------------------------------------------------------- každých 5 minút: zlacnenia do mobilov a neprevzaté kontakty záložnému maklérovi
create or replace function public._kontakty_trh_kolo() returns integer
language plpgsql security definer set search_path = public as $$
declare r record; n int := 0; v_z uuid := _kontakty_zaloha();
begin
  if v_z is not null then
    for r in select id from odhady_hodnoty where trh_od is not null and predane is null and trh_koniec <= now() order by id for update skip locked loop
      perform _kontakt_odovzdaj(r.id, v_z, 0, false, 'zaloha');
      n := n + 1;
    end loop;
  end if;
  for r in select id from odhady_hodnoty where trh_od is not null and predane is null and trh_koniec > now() order by id loop
    perform _kontakt_oznam(r.id);
  end loop;
  return n;
end $$;
select cron.schedule('kontakty-trh', '*/5 * * * *', 'select public._kontakty_trh_kolo()');

