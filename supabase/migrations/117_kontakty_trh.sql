-- Kontakty na predaj (6. 11. 2026) – žiadosti o odhad hodnoty ako platené kontakty pre realitné kancelárie
--  * v okresoch zapnutých v Správe zákazníkov → Kontakty žiadosť nedostane maklér hneď, ale ide „na predaj“:
--    kancelárie s týmto okresom vidia náhľad bez osobných údajov a prvá, ktorá klikne „Prevziať“, zaplatí aktuálnu cenu z kreditu
--  * klesajúca cena (predvolene 50 € → po 4 h 35 € → po 12 h 20 € → po 24 h 10 €, s DPH); keď žiadosť príde v noci (21:00 – 7:00),
--    hodiny sa rátajú od 7:00 (v noci ju nikto nevidí v mobile a cena by klesla „naprázdno“)
--  * prvé 2 kontakty pre kanceláriu zadarmo, potom z kreditu (kredit pripíše hlavný správca po platbe)
--  * nikto neprevzal do 48 h → dostane ju záložný maklér (hlavný správca), aby klient nečakal
--  * reklamácia do 48 h od prevzatia – hlavný správca uzná (kredit sa vráti) alebo zamietne
--  * mobil: nový kontakt na predaj a zlacnenie (7:00 – 21:00) maklérom kancelárií s týmto okresom
--  * okresy mimo predaja fungujú po starom (žiadosť hneď dostane maklér z obce, _odhad_makler)
-- Kým žiadosť nikto neprevzal, patrí skrytej kancelárii „Kontakty na predaj (Týpek)“ (neaktívna, bez maklérov) – nikto ju nevidí,
-- náhľad dávajú len funkcie nižšie. Prevzatím sa presunie do kancelárie kupujúceho (strážca kancelárie to dovolí len tu).

